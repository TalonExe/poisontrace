from __future__ import annotations
"""Application-owned interfaces implemented by external adapters."""

from dataclasses import dataclass
from typing import Any, Protocol
from contextlib import AbstractAsyncContextManager

from poisontrace.application.contracts import RunResponse
from poisontrace.domain import AgentDecision, ExperimentResult, Scenario, ToolDefinition
from poisontrace.domain import (SyntheticCase, InvestigationInput, EvidenceTool, InvestigationCall,
    EvidenceObservation, InvestigationStep)


class ExecutionBusy(RuntimeError):
    pass


class JobStore(Protocol):
    def find_intent(self, owner: int, intent: str, fingerprint: str) -> dict | None: ...
    def admit(self, owner: int, intent: str, fingerprint: str, snapshot: dict) -> dict: ...
    def admit_group(self, owner: int, intent: str, fingerprint: str, snapshot: dict, identifier: str | None = None) -> dict: ...
    def admit_campaign(self, owner: int, intent: str, fingerprint: str, snapshot: dict) -> dict: ...
    def start_campaign_attempt(self, claim: dict, ordinal: int) -> None: ...
    def start_group_attempt(self, claim: dict, attempt: int) -> None: ...
    def get(self, identifier: str, owner: int) -> dict: ...
    def list(self, owner: int) -> list[dict]: ...
    def claim(self) -> dict | None: ...
    def begin_attempt(self, claim: dict) -> None: ...
    def fail_claim(self, claim: dict, category: str = 'investigation_execution_error') -> None: ...
    def reconcile(self) -> None: ...


class InvestigationModel(Protocol):
    async def next_step(self, case: InvestigationInput, tools: tuple[EvidenceTool, ...],
                        observations: tuple[EvidenceObservation, ...]) -> InvestigationStep: ...


class EvidenceSession(Protocol):
    identity: dict
    async def discover(self) -> tuple[EvidenceTool, ...]: ...
    async def invoke(self, call: InvestigationCall) -> EvidenceObservation: ...


class EvidenceTransport(Protocol):
    def open(self, case: SyntheticCase, *, attack_family: str | None = None) -> AbstractAsyncContextManager[EvidenceSession]: ...


class InvestigationCases(Protocol):
    def list(self) -> list[dict]: ...
    def get(self, case_id: str) -> SyntheticCase: ...
    def save_ground_truth(self, case: SyntheticCase, base_version: str) -> SyntheticCase: ...


class AgentModel(Protocol):
    def respond(self, scenario: Scenario, tools: tuple[ToolDefinition, ...]) -> AgentDecision: ...


class ModelFactory(Protocol):
    def __call__(self, provider: str, model: str | None, api_key: str | None = None) -> AgentModel: ...


class UsableScenarioLookup(Protocol):
    def load_usable(self, scenario_id: str) -> Scenario: ...


class ScenarioRepository(Protocol):
    """Document persistence, including invalid drafts and filename-based reload."""
    def list(self) -> list[dict[str, Any]]: ...
    def get(self, scenario_id: str) -> dict[str, Any]: ...
    def save(self, document: dict[str, Any], filename: str | None = None) -> dict[str, Any]: ...
    def write_document(self, filename: str, document: dict[str, Any]) -> None: ...
    def delete_filename(self, filename: str) -> None: ...
    def load(self, filename: str) -> Scenario: ...


@dataclass(frozen=True)
class TraceEvent:
    kind: str
    data: dict[str, object]
    run_key: str | None = None


class TraceStore(Protocol):
    def record(self, event: TraceEvent) -> None: ...
    def save_result(self, result: ExperimentResult, run_key: str | None = None) -> int: ...


class RunStore(TraceStore, Protocol):
    def activity_for(self, owner_id: int, start: int, end: int) -> dict: ...
    def run_ids_for(self, owner_id: int) -> list[int]: ...
    def owner_for(self, run_id: int) -> int | None: ...
    def run_ids(self) -> list[int]: ...
    def result_for(self, run_id: int) -> ExperimentResult: ...
    def events_for(self, run_id: int) -> list[TraceEvent]: ...


@dataclass(frozen=True)
class CredentialReference:
    credential_id: str
    provider: str
    label: str
    masked: str


class SecretsAdapter(Protocol):
    """Every operation uses the trusted principal_scope analyst identity.

    Filter before metadata/decryption. Deny missing, foreign and ownerless
    references with CredentialNotFound. Absent and non-analyst principals have
    no credential authority. Injected adapters are trusted application code.
    """
    def save(self, provider: str, secret: str, label: str = "") -> CredentialReference: ...
    def retrieve(self, credential_id: str) -> str: ...
    def reference(self, credential_id: str) -> CredentialReference: ...
    def list(self) -> list[CredentialReference]: ...
    def replace(self, credential_id: str, provider: str, secret: str, label: str = "") -> CredentialReference: ...
    def revoke(self, credential_id: str) -> None: ...


class CampaignStore(Protocol):
    def owner_for(self, campaign_id: str) -> int | None: ...
    def ids_for(self, owner_id: int) -> list[str]: ...
    def create(self, *, provider: str, model: str, credential_id: str | None, scenarios: list[tuple[str, str]]) -> str: ...
    def get(self, campaign_id: str) -> dict: ...
    def list(self) -> list[dict]: ...
    def set_status(self, campaign_id: str, status: str) -> None: ...
    def associate_child_run(self, campaign_id: str, ordinal: int, *, child_run_id: int | None = None, error: str | None = None) -> None: ...


class CampaignScenarios(Protocol):
    """Filename-based selection and reload, preserving loader errors."""
    def select_poisoned(self) -> tuple[list[tuple[str, str]], list[str]]: ...
    def load(self, filename: str) -> Scenario: ...


class RunSummary(Protocol):
    def __call__(self, run_id: int, result: ExperimentResult | None = None) -> RunResponse: ...


class ManagedSecretClient(Protocol):
    """Application-owned client for a managed secret service."""

    def put_secret(self, credential_id: str, provider: str, label: str, secret: str) -> None: ...
    def get_secret(self, credential_id: str) -> str: ...
    def delete_secret(self, credential_id: str) -> None: ...


class RunGroupStore(Protocol):
    def owner_for(self, identifier: str) -> int | None: ...
    def ids_for(self, owner_id: int) -> list[str]: ...
    def create(self, plan: dict) -> str: ...
    def get(self, identifier: str) -> dict: ...
    def list(self) -> list[dict]: ...
