"""Application-owned interfaces implemented by external adapters."""

from dataclasses import dataclass
from typing import Any, Protocol

from poisontrace.application.contracts import RunResponse
from poisontrace.domain import AgentDecision, ExperimentResult, Scenario, ToolDefinition


class AgentModel(Protocol):
    def respond(self, scenario: Scenario, tools: tuple[ToolDefinition, ...]) -> AgentDecision: ...


class ModelFactory(Protocol):
    def __call__(self, provider: str, model: str | None, api_key: str | None = None) -> AgentModel: ...


class UsableScenarioLookup(Protocol):
    def load_usable(self, scenario_id: str) -> Scenario: ...


class ScenarioRepository(Protocol):
    """Document persistence, including invalid drafts and filename-based reload."""
    def list(self) -> list[dict[str, Any]]: ...
    def get(self, scenario_id: str) -> dict[str, Any]: ...
    def save(self, document: dict[str, Any], filename: str | None = None) -> dict[str, Any]: ...
    def write_document(self, filename: str, document: dict[str, Any]) -> None: ...
    def delete_filename(self, filename: str) -> None: ...
    def load(self, filename: str) -> Scenario: ...


@dataclass(frozen=True)
class TraceEvent:
    kind: str
    data: dict[str, str]
    run_key: str | None = None


class TraceStore(Protocol):
    def record(self, event: TraceEvent) -> None: ...
    def save_result(self, result: ExperimentResult, run_key: str | None = None) -> int: ...


class RunStore(TraceStore, Protocol):
    def run_ids(self) -> list[int]: ...
    def latest_run_id(self) -> int: ...
    def result_for(self, run_id: int) -> ExperimentResult: ...
    def events_for(self, run_id: int) -> list[TraceEvent]: ...


@dataclass(frozen=True)
class CredentialReference:
    credential_id: str
    provider: str
    label: str
    masked: str


class SecretsAdapter(Protocol):
    def save(self, provider: str, secret: str, label: str = "") -> CredentialReference: ...
    def retrieve(self, credential_id: str) -> str: ...
    def reference(self, credential_id: str) -> CredentialReference: ...
    def list(self) -> list[CredentialReference]: ...
    def replace(self, credential_id: str, provider: str, secret: str, label: str = "") -> CredentialReference: ...
    def revoke(self, credential_id: str) -> None: ...


class CampaignStore(Protocol):
    def create(self, *, provider: str, model: str, credential_id: str | None, scenarios: list[tuple[str, str]]) -> str: ...
    def get(self, campaign_id: str) -> dict: ...
    def list(self) -> list[dict]: ...
    def set_status(self, campaign_id: str, status: str) -> None: ...
    def associate_child_run(self, campaign_id: str, ordinal: int, *, child_run_id: int | None = None, error: str | None = None) -> None: ...


class CampaignScenarios(Protocol):
    """Filename-based selection and reload, preserving loader errors."""
    def select_poisoned(self) -> list[tuple[str, str]]: ...
    def load(self, filename: str) -> Scenario: ...


class RunSummary(Protocol):
    def __call__(self, run_id: int, result: ExperimentResult | None = None) -> RunResponse: ...


class ManagedSecretClient(Protocol):
    """Application-owned client for a managed secret service."""

    def put_secret(self, credential_id: str, provider: str, label: str, secret: str) -> None: ...
    def get_secret(self, credential_id: str) -> str: ...
    def delete_secret(self, credential_id: str) -> None: ...
